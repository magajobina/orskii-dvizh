param([string]$Face = 'output/imagegen/akashev-face-crop.png', [string]$Output = 'src/assets/illustrations/g4-za-shkafom-akashev-fotomontazh.png')
Add-Type -AssemblyName System.Drawing
$basePhoto = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath 'src/assets/illustrations/g4-za-shkafom-nashel-siyaniye.png').Path)
$facePhoto = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $Face).Path)
