$faceOutline = [System.Drawing.Drawing2D.GraphicsPath]::new()
$faceOutline.AddBezier(91,14,39,12,27,42,26,88)
$faceOutline.AddBezier(26,88,11,84,17,119,25,127)
$faceOutline.AddBezier(25,127,28,171,47,209,91,219)
